static const char *TAG = "LCD";

// ILI9341 Commands
#define ILI9341_SWRESET     0x01
#define ILI9341_SLPOUT      0x11
#define ILI9341_DISPON      0x29
#define ILI9341_CASET       0x2A
#define ILI9341_PASET       0x2B
#define ILI9341_RAMWR       0x2C
#define ILI9341_MADCTL      0x36
#define ILI9341_PIXFMT      0x3A

static spi_device_handle_t lcd_spi = NULL;

// Backlight PWM config
#define LCD_BL_LEDC_TIMER      LEDC_TIMER_1
#define LCD_BL_LEDC_MODE       LEDC_LOW_SPEED_MODE
#define LCD_BL_LEDC_CHANNEL    LEDC_CHANNEL_1
#define LCD_BL_LEDC_FREQ_HZ    5000
#define LCD_BL_LEDC_RES        LEDC_TIMER_8_BIT

static bool backlight_pwm_initialized = false;

void lcd_set_backlight(uint8_t brightness) {
    // brightness: 0 (off) to 255 (full)
    if (!backlight_pwm_initialized) return;
    ledc_set_duty(LCD_BL_LEDC_MODE, LCD_BL_LEDC_CHANNEL, brightness);
    ledc_update_duty(LCD_BL_LEDC_MODE, LCD_BL_LEDC_CHANNEL);
}

